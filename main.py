
# # class  مثل یک نقشه میمونه
# # ما دو چیز را در این جلسه بررسی میکنیم
# """یکی کلاسها و دیگری ابجکت یا شی"""
# """کلاسها مثله یک نقشه یا زمین میمونه و شی مثل اجر سیمان و بلوک"""
# =====================
class A: #کلاس
    name = "ayom" # اتربیوت یا پراپرتی
    age = 24
x = A() 
# x =  نمونه یا ابجکت
# از طریق نمونه میتوانم به اتربیوت دسترسی داشته باشم
print(f"my name is : {x.name} and age is: {x.age}")
